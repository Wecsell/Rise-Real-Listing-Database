"""
Проверка дословных цитат, которыми модель обязана подпирать каждое извлечённое
значение (implementation_plan.md, «Правила, следующие из этого», п.2).

Смысл: задача слабой модели - извлечение, а не суждение. Значение, под которое
не нашлось цитаты в исходном тексте, в базу не пишется вообще - уходит в Gaps
и в вопрос агенту. Критерий прохождения по плану - поведение системы, а не
модели: если модель ошиблась, но валидация не дала записать мусор, это успех.

Логика переехала сюда из tools_benchmark_models.py, где она отлаживалась на
живом наборе кейсов. Именно эта функция четыре раза подряд оказывалась причиной
«провала модели», который на деле был дефектом измерителя (см. план, «Главный
урок не про модели, а про измерение»), поэтому копировать её в прод нельзя -
копия разойдётся с проверенной версией. Бенчмарк импортирует отсюда же.
"""
import re
from typing import Any, List, Union

# Порог суммарной длины цитат. Не на каждую по отдельности: значение ячейки
# таблицы коротко по своей природе ("580", "M²"), и персональный минимум
# браковал настоящие дословные цитаты как выдумку.
MIN_TOTAL_QUOTE_LENGTH = 10

OK = "ok"
SPLICED = "spliced"
BAD = "bad"


def normalize(s: str) -> str:
    return re.sub(r"\s+", " ", (s or "")).strip().lower()


def check_quotes(quotes: Union[str, List[Any], None], source: str) -> str:
    """
    Трёхуровневая проверка цитат: 'ok' | 'spliced' | 'bad'.

    Список, а не одна строка: составной ответ (два документа, шапка таблицы плюс
    строка данных) честно требует нескольких фрагментов. Ранняя версия принимала
    только одну цитату и отвергала корректные составные ответы.

    Три уровня, а не два, потому что у таблиц дословная непрерывная цитата
    структурно невозможна: при извлечении текста из PDF двумерная структура
    теряется, заголовок колонки и значение расходятся далеко друг от друга.
      ok      - фрагмент встречается в источнике дословно и подряд
      spliced - все слова фрагмента есть в источнике, но не подряд (нормально
                для таблиц, подозрительно для связного текста)
      bad     - слов нет в источнике вовсе, то есть выдумка
    """
    if isinstance(quotes, str):
        quotes = [quotes] if quotes else []
    if not quotes:
        return BAD
    src = normalize(source)
    src_tokens = set(re.findall(r"[\wÀ-￿]+", src))

    if sum(len(normalize(str(q))) for q in quotes) < MIN_TOTAL_QUOTE_LENGTH:
        return BAD

    worst = OK
    for q in quotes:
        qn = normalize(str(q))
        if not qn:
            return BAD
        if qn in src:
            continue
        tokens = re.findall(r"[\wÀ-￿]+", qn)
        if tokens and all(t in src_tokens for t in tokens):
            worst = SPLICED
        else:
            return BAD
    return worst


def is_verifiable_source(source: str) -> bool:
    """
    Есть ли вообще с чем сверять цитату.

    На чистом скане текстового слоя нет, и проверка цитат невозможна в принципе -
    не «прошла» и не «провалилась», а неприменима. План отмечает это как отдельный
    риск: в замере 3 из 5 ответов на сканах оказались непроверяемыми, включая
    мастер-лиз и скриншот разрешений, то есть самые рискованные документы.
    Такое значение нельзя молча считать подтверждённым.
    """
    return len(normalize(source)) >= MIN_TOTAL_QUOTE_LENGTH
